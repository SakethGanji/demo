// U2 ad-hoc walk (not a suite): drives the UI at 1366 × 900, logs every /api call the UI makes, takes the screenshots.
//   node walk.cjs <shots dir> <files dir> <calls.txt> <credit-risk team id> <collections team id> [from step]
const { chromium } = require('playwright')
const fs = require('fs')
const path = require('path')
const [out, files, callsOut, CR, CO, FROM] = process.argv.slice(2)
const ui = 'http://127.0.0.1:5190'
const from = Number(FROM || 0)

;(async () => {
  fs.mkdirSync(out, { recursive: true })
  const b = await chromium.launch()
  const p = await b.newPage({ viewport: { width: 1366, height: 900 }, deviceScaleFactor: 1 })
  const calls = []
  const mark = (s) => { calls.push(`\n## ${s}`); console.log('##', s) }
  const noisy = /\.tsx?(\?|$)|\/api\/(health|status|runs\?kind=all&light|runs\/[^/]+\/events|llm|agent|vela|annotations|me$|authz\/check)/
  const short = (j) => JSON.stringify(j).slice(0, 420)
  p.on('response', async (r) => {
    const u = r.url(); if (!u.includes('/api/') || noisy.test(u)) return
    const q = r.request(); let body = q.postData() || ''
    if ((q.headers()['content-type'] || '').startsWith('multipart')) body = '(multipart: ' + [...body.matchAll(/name="([^"]+)"(?:; filename="([^"]+)")?\r\n(?:Content-Type: [^\r]+\r\n)?\r\n([^\r]{0,40})/g)].map((m) => m[2] ? `${m[1]}=@${m[2]}` : `${m[1]}=${m[3]}`).join(' ') + ')'
    let res = ''
    try { res = short(await r.json()) } catch { /* not json */ }
    calls.push(`${q.method()} ${u.replace(/^.*\/api/, '/api')} ${body ? body.slice(0, 300) + ' ' : ''}→ ${r.status()}${res ? ' ' + res : ''}`)
  })
  const errors = []
  p.on('console', (m) => { if (m.type() === 'error') errors.push(`[${p.url().replace(ui, '')}] ${m.text()}`) })
  p.on('pageerror', (e) => errors.push(`pageerror ${e.message}`))
  const shot = async (name, el) => {
    await p.waitForTimeout(700)
    let opts = { fullPage: false }
    if (el) { const l = p.locator(el).first(); await l.scrollIntoViewIfNeeded(); await l.evaluate((e) => { const r = e.getBoundingClientRect(); if (r.top < 70) { let s = e.parentElement; while (s && s.scrollHeight <= s.clientHeight) s = s.parentElement; (s || window).scrollBy(0, r.top - 80) } }); await p.waitForTimeout(200); const bb = await l.boundingBox(); opts = { clip: { x: bb.x, y: bb.y, width: Math.min(bb.width, 1366), height: Math.min(bb.height, 2400) } } }
    await p.screenshot({ path: path.join(out, `${name}.png`), ...opts }); console.log('shot', name)
  }
  const as = async (who, team, hash) => {
    await p.goto(`${ui}/#/${hash}`)
    await p.evaluate(([w, t]) => { localStorage.setItem('ensemble.actor', w); localStorage.setItem('ensemble.team', t) }, [who, team]); await p.reload()
    await p.waitForTimeout(1500)
  }
  const tid = (s) => `[data-testid="${s}"]`
  const st = fs.existsSync(path.join(out, 'state.json')) ? JSON.parse(fs.readFileSync(path.join(out, 'state.json'))) : {}
  const save = () => fs.writeFileSync(path.join(out, 'state.json'), JSON.stringify(st, null, 1))
  if (fs.existsSync(path.join(out, 'state.json'))) Object.assign(st, JSON.parse(fs.readFileSync(path.join(out, 'state.json'), 'utf8')))
  const openDs = async (who, team) => { await as(who, team, `build?view=data&dataset=${st.root}`); await p.waitForSelector(tid('data-page'), { timeout: 30000 }) }

  try {
  if (from <= 1) {
    mark('1. Ana · Build › Data: New project, Upload… book.xlsx + bureau.csv → one check, three tables')
    await as('Ana', CR, 'build?view=data')
    await p.waitForSelector(tid('data-table'), { timeout: 30000 })
    await p.click(tid('project-new')); await p.fill(tid('project-new-name'), 'PD 2026'); await p.click(tid('project-new-create'))
    await p.waitForSelector('text=Project prj_', { timeout: 15000 })
    await p.click(tid('data-upload'))
    await p.setInputFiles(tid('up-file'), [path.join(files, 'book.xlsx'), path.join(files, 'bureau.csv')])
    await p.waitForSelector(`${tid('up-project')} option:has-text("PD 2026")`, { state: 'attached', timeout: 30000 })
    await p.selectOption(tid('up-project'), { label: 'PD 2026' })
    await p.click(tid('up-check'))
    await p.waitForSelector(tid('up-plan'), { timeout: 120000 })
    await shot('01-multi-check', tid('up-flow'))
    mark('1b. keys on the three tables, both suggested relations declared → Check again')
    for (const [t, k] of [['applications', 'app_id'], ['payments', 'payment_id'], ['bureau', 'customer_id']]) { await p.fill(tid(`up-key-${t}`), k); await p.locator(tid(`up-key-${t}`)).blur() }
    for (const r of ['payments_applications', 'applications_bureau']) await p.locator(`${tid(`up-rel-${r}`)} input`).check()
    await p.click(tid('up-recheck'))
    await p.waitForSelector(`${tid('up-plan')} .data-ok`, { timeout: 120000 })
    await shot('02-plan-keys-relations', tid('up-plan'))
    await p.click(tid('up-commit'))
    await p.waitForSelector(tid('data-page'), { timeout: 120000 })
    st.root = await p.getAttribute(tid('data-page'), 'data-root'); save()
    await p.waitForSelector(tid('data-tables'), { timeout: 30000 })
    await shot('03-created-tables', tid('data-tables'))
  }
  if (from <= 2) {
    mark('2. Ana · Upload a new version… bureau_delta.csv → looks_like_delta → Apply as delta (bureau) → counts → Create v2')
    await openDs('Ana', CR)
    await p.click(tid('data-upload-version'))
    await p.setInputFiles(tid('up-file'), [path.join(files, 'bureau_delta.csv')])
    await p.click(tid('up-check'))
    await p.waitForSelector(tid('up-delta-hint'), { timeout: 120000 })
    await p.waitForSelector(`${tid('up-delta-table')} option[value="bureau"]`, { state: 'attached' })
    await p.selectOption(tid('up-delta-table'), 'bureau')
    await shot('04-looks-like-delta', tid('up-flow'))
    await p.click(tid('up-apply-delta'))
    await p.waitForSelector(tid('up-delta-bureau'), { timeout: 120000 })
    await shot('05-delta-counts', tid('up-plan'))
    await p.click(tid('up-commit'))
    await p.waitForSelector(`${tid('data-msg')}:has-text("Delta on bureau")`, { timeout: 120000 })
    await shot('06-delta-created', tid('data-msg'))
    mark('2b. table picker → bureau: diff v1 → v2 of bureau')
    await p.waitForSelector(tid('table-picker'), { timeout: 30000 })
    await p.selectOption(tid('table-picker'), 'bureau')
    await p.waitForSelector(tid('diff-table'), { timeout: 60000 })
    await p.waitForSelector(tid('diff-changed'), { timeout: 60000 })
    await shot('07-diff-bureau', tid('data-diff'))
  }
  if (from <= 3) {
    mark('3. Ana · Joins: a bad join (payments as a lookup) → 400 one_to_many; then bureau n:1 + payments aggregated → coverage')
    await openDs('Ana', CR)
    await p.waitForSelector(tid('join-builder'), { timeout: 30000 })
    await p.click(tid('join-new'))
    await p.fill(tid('join-name'), 'apps_full')
    await p.click(tid('join-add-payments'))
    await p.selectOption(tid('join-type-0'), 'n:1')
    await p.click(tid('join-save'))
    await p.waitForSelector(tid('join-err'), { timeout: 60000 })
    await shot('08-join-400', tid('join-form'))
    await p.selectOption(tid('join-type-0'), 'aggregate')
    await p.locator(`${tid('join-agg-0-0')} input`).fill('n_pay')
    await p.click(tid('join-agg-add-0'))
    await p.locator(`${tid('join-agg-0-1')} input`).fill('late_mean')
    await p.locator(`${tid('join-agg-0-1')} select`).first().selectOption('mean'); await p.locator(`${tid('join-agg-0-1')} select`).nth(1).selectOption('days_late')
    await p.click(tid('join-agg-add-0'))
    await p.locator(`${tid('join-agg-0-2')} input`).fill('late_max')
    await p.locator(`${tid('join-agg-0-2')} select`).first().selectOption('max'); await p.locator(`${tid('join-agg-0-2')} select`).nth(1).selectOption('days_late')
    await p.fill(tid('join-prefix-0'), 'pay__')
    await p.click(tid('join-add-bureau'))
    await shot('09-join-form', tid('join-form'))
    await p.click(tid('join-save'))
    await p.waitForSelector(tid('join-coverage'), { timeout: 120000 })
    await shot('10-join-coverage', tid('join-detail'))
    mark('4. build the frame on v2 → preview (masked)')
    await p.click(tid('join-frame'))
    await p.waitForSelector(tid('frame-preview'), { timeout: 120000 })
    await shot('11-frame-preview', tid('frame-result'))
    mark('5. train on the join (label defaulted, 60 s)')
    await p.selectOption(`${tid('train-join')} ${tid('train-label')}`, 'defaulted')
    await p.click(`${tid('train-join')} ${tid('train-start')}`)
    await p.waitForURL(/models\?run=/, { timeout: 60000 })
    st.run = new URL(p.url().replace('#/', '')).searchParams.get('run'); save()
  }
  if (from <= 6) {
    mark('6. Ana · register the join run → the card: input record, parity ok, inputs.zip')
    for (let i = 0; i < 180; i++) { const r = await (await fetch(`http://127.0.0.1:8000/api/runs/${st.run}`)).json(); if (r.status === 'succeeded') break; if (r.status === 'failed') throw new Error('run failed'); await p.waitForTimeout(2000) }
    await as('Ana', CR, `registry?register=${st.run}`)
    await p.waitForSelector(tid('register-submit'), { timeout: 60000 })
    await p.fill(tid('register-name'), 'pd-join')
    await p.click(tid('register-submit'))
    await p.waitForSelector(tid('version-detail'), { timeout: 120000 })
    for (let i = 0; i < 120 && !(await p.locator('[role="tab"]:has-text("Model Card")').count()); i++) await p.waitForTimeout(2000)
    st.version = new URLSearchParams(p.url().split('?')[1] || '').get('version'); save()
    await p.click('[role="tab"]:has-text("Model Card")')
    await p.waitForSelector(tid('card-inputs'), { timeout: 120000 })
    await shot('12-card-inputs-parity', tid('card-inputs'))
    mark('7. batch: three files (applications, bureau, payments) through the saved join')
    await p.click('[role="tab"]:has-text("Batch & Drift")')
    await p.waitForSelector(tid('batch-files'), { state: 'attached', timeout: 60000 })
    await p.setInputFiles(tid('batch-files'), ['applications.csv', 'bureau.csv', 'payments.csv'].map((f) => path.join(files, 'batch', f)))
    await p.waitForSelector(tid('batch-table-map'), { timeout: 30000 })
    await shot('13-batch-map', tid('batch-table-map'))
    await p.click(tid('batch-submit'))
    await p.waitForSelector(tid('batch-join'), { timeout: 300000 })
    await shot('14-batch-join', tid('batch-join'))
  }
  if (from <= 8) {
    mark('8. lineage: v1 / v2 → join frame → run → registered version; usage via_join')
    await openDs('Ana', CR)
    await p.waitForSelector('[data-testid^="pt-frame-"]', { timeout: 60000 })
    await shot('15-lineage-frame', tid('project-tree'))
    await p.waitForSelector(tid('usage-frame'), { timeout: 30000 })
    await shot('16-usage-join-frame', tid('data-usage'))
    mark('9. governance as Ana: confirm the PII tags, freeze the contract, ask for certification, ask to share with Collections (masked)')
    await p.waitForSelector(`${tid('pii-confirm')}:not([disabled])`, { timeout: 30000 })
    await p.click(tid('pii-confirm'))
    await p.waitForSelector(`${tid('pii-panel')} :text("confirmed by Ana")`, { timeout: 30000 })
    await p.click(tid('contract-freeze'))
    await p.waitForSelector(tid('contract-result'), { timeout: 60000 })
    await p.fill(tid('cert-reason'), 'PD 2026 development data')
    await p.click(tid('cert-request'))
    await p.waitForSelector(`${tid('cert-panel')} .cert-pending`, { timeout: 60000 })
    await p.selectOption(tid('share-team'), CO)
    await p.fill(tid('share-reason'), 'collections strategy model')
    await p.click(tid('share-request'))
    await p.waitForSelector(`${tid('share-panel')} .cert-pending`, { timeout: 30000 })
    await shot('17-governance-ana', tid('governance'))
    mark('10. governance as Ben (owner): approve the certification and the share (Ana could not: four eyes)')
    await openDs('Ben', CR)
    await p.waitForSelector(`${tid('cert-approve')}:not([disabled])`, { timeout: 30000 })
    await p.click(tid('cert-approve'))
    await p.waitForSelector(`${tid('cert-panel')} .cert-active`, { timeout: 60000 })
    await p.waitForSelector(`${tid('share-approve')}:not([disabled])`, { timeout: 30000 })
    await p.click(tid('share-approve'))
    await p.waitForSelector(`${tid('share-panel')} .cert-active`, { timeout: 30000 })
    await shot('18-governance-ben', tid('governance'))
  }
  if (from <= 10) {
    mark('10b. Ana (maintainer) unmasks with a reason: clear values, the read audited')
    await openDs('Ana', CR)
    await p.click(tid('data-edit-2'))
    await p.waitForSelector(`${tid('unmask')}:not([disabled])`, { timeout: 60000 })
    await p.click(tid('unmask'))
    await p.fill(tid('unmask-reason'), 'QA of the bureau delta')
    await p.click(tid('unmask-go'))
    await p.waitForSelector(`${tid('unmasked-on')} :text("unmasked")`, { timeout: 60000 })
    await shot('23-ana-unmasked', tid('data-editor'))
  }
  if (from <= 11) {
    mark('11. Carl (Collections): the shared dataset in the catalog, masked rows, Unmask (reason) refused')
    await as('Carl', CO, 'build?view=data')
    await p.waitForSelector(tid('data-table'), { timeout: 30000 })
    await p.click(tid('data-scope-all'))
    await p.waitForSelector(tid(`data-row-${st.root}`), { timeout: 30000 })
    await p.waitForSelector(tid(`data-shared-${st.root}`), { timeout: 30000 })
    await shot('19-carl-catalog', tid('data-table'))
    await p.click(tid(`data-row-${st.root}`))
    await p.waitForSelector(tid('data-edit-2'), { timeout: 30000 })
    await p.click(tid('data-edit-2'))
    await p.waitForSelector(tid('masked-col-ssn'), { timeout: 60000 })
    await p.waitForSelector(tid('unmask-why'), { timeout: 30000 })
    await shot('20-carl-masked-greyed', tid('data-editor'))
    await p.click(tid('edit-close'))
    mark('11b. the same, with /authz/check stubbed to a stale "allow" (walk only): the API refuses → still masked, unmasked_refused shown')
    await p.route('**/api/authz/check', (r) => r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ action: 'data.read_unmasked', allow: true, mode: 'audit', reason: 'stub' }) }))
    await p.click(tid('data-edit-2'))
    await p.waitForSelector(`${tid('unmask')}:not([disabled])`, { timeout: 30000 })
    await p.click(tid('unmask'))
    await p.fill(tid('unmask-reason'), 'collections QA')
    await p.click(tid('unmask-go'))
    try { await p.waitForSelector(tid('unmasked-refused'), { timeout: 8000 }) } catch { console.log('11b (enforce): no unmasked_refused panel: the API answered 403 (enforce semantics)') }
    await shot('21-carl-unmasked-refused', tid('data-editor'))
    await p.unroute('**/api/authz/check')
    await p.click(tid('edit-close'))
    mark('12. Carl trains the shared version into his own project (project_id)')
    await p.selectOption(tid('table-picker'), 'applications')
    await p.waitForSelector(`${tid('train-table')} ${tid('train-project')} option`, { state: 'attached', timeout: 30000 })
    await p.selectOption(`${tid('train-table')} ${tid('train-label')}`, 'defaulted')
    await p.fill(`${tid('train-table')} input[type=number]`, '30')
    await shot('22-carl-train-shared', tid('data-tables'))
    await p.click(`${tid('train-table')} ${tid('train-start')}`)
    await p.waitForURL(/models\?run=/, { timeout: 60000 })
    st.carlRun = new URL(p.url().replace('#/', '')).searchParams.get('run'); save()
  }
  if (from <= 13) {
    mark('13. Settings › Teams: Ana (New team greyed), Ada (members, policy, legal holds)')
    await as('Ana', CR, 'settings')
    await p.waitForSelector(tid('settings-teams'), { timeout: 30000 })
    await shot('24-teams-ana', tid('settings-teams'))
    await as('Ada', CR, 'settings')
    await p.waitForSelector(tid(`team-row-${CR}`), { timeout: 30000 })
    await p.click(tid(`team-row-${CR}`))
    await p.waitForSelector(tid('members-table'), { timeout: 30000 })
    await p.waitForSelector(tid('holds-panel'), { timeout: 30000 })
    await shot('25-teams-ada', tid('settings-teams'))
    mark('13b. Ada places a legal hold on the dataset (P24): it then blocks a delete of v1')
    await p.selectOption(tid('hold-kind'), 'dataset')
    await p.fill(tid('hold-scope'), st.root)
    await p.fill(tid('hold-case'), 'CASE-2026-114')
    await p.fill(tid('hold-reason'), 'regulator inquiry on PD 2026')
    await p.click(tid('hold-place'))
    await p.waitForSelector('[data-testid^="hold-hd_"], [data-testid^="hold-lh_"], [data-testid^="hold-"]:has-text("CASE-2026-114")', { timeout: 30000 })
    await shot('26-holds', tid('holds-panel'))
    await openDs('Ana', CR)
    await p.selectOption(tid('data-remove-target'), { index: 1 })
    await p.fill(tid('data-remove-reason'), 'old extract, not needed')
    await p.click(tid('data-delete'))
    await p.waitForSelector(`${tid('data-msg')}`, { timeout: 30000 })
    await shot('27-delete-held', tid('data-msg'))
  }
  } catch (e) { console.error('FAILED', e.message); await p.screenshot({ path: path.join(out, `zz-fail.png`), fullPage: true }) }
  fs.writeFileSync(callsOut, calls.join('\n') + `\n\nconsole errors: ${errors.length}\n` + errors.join('\n'))
  console.log('errors', errors.length, errors.slice(0, 10))
  await b.close()
})()
