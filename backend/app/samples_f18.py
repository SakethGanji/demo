"""F18's sample: a loan book and a simulated 12-month stream of new applications, with drift from month 7.

The **training sample** (`loan-stream`) holds 9,000 applications dated 2024-01-01 … 2024-12-31, each with its observed
outcome (`defaulted`). The **stream** is twelve monthly batches of new applications, 2025-01 … 2025-12, generated by
the same seeded process; it has no label when it arrives. The outcome of a month's applications is known only later
(default = 90 days past due within the observation window), so the labels of month m arrive as a separate file on
the last day of month m + 3, keyed by `application_id`.

What changes from month 7 (2025-07), and is recorded in `stream_truth.json`:
- **covariate drift** (p(x) changes, p(y | x) does not): `debt_to_income` rises (Beta(2.2, 5.0) + δ_m, δ = 0.08 in
  month 7 growing to 0.14 in month 12) and `credit_score` falls (−15 points in month 7 growing to −40). PSI and the
  adversarial AUC see this as soon as the batch is scored; the model's ranking stays valid because the outcome still
  follows the same law.
- **concept change** (p(y | x) changes, p(x) does not): applications from the `online` channel default more for the
  same features (logit + 1.3, a first-party-fraud wave the recorded features carry nothing about). The channel mix
  stays the same, so PSI and the adversarial classifier cannot see it; only performance on labelled rows can, and
  only once month 7's labels arrive (end of month 10).

Everything is seeded: `generate_loan_stream(seed)` and `stream_month(m, seed)` always give the same rows.
"""

from __future__ import annotations

import calendar
from datetime import date, timedelta
from typing import Any

import numpy as np
import pandas as pd

COEFS = {
    "intercept": -2.3,
    "credit_score_per_100": -1.6,     # (credit_score − 690) / 100
    "debt_to_income": 3.2,            # (dti − 0.30)
    "utilization": 1.4,               # (util − 0.35)
    "prior_defaults": 0.6,
    "employment=unemployed": 1.0,
    "employment=self-employed": 0.3,
    "term_months_per_12": 0.08,       # (term − 36) / 12
}
CHANNELS = ["branch", "online", "broker"]
CHANNEL_P = [0.40, 0.45, 0.15]
TRAIN_START = date(2024, 1, 1)
STREAM_START = (2025, 1)
N_TRAIN = 9_000
N_MONTH = 1_200
DRIFT_MONTH = 7
LABEL_LAG_MONTHS = 3
# month index (1…12) → shift; months before DRIFT_MONTH have none
DTI_SHIFT = {7: 0.08, 8: 0.09, 9: 0.10, 10: 0.11, 11: 0.12, 12: 0.14}
SCORE_SHIFT = {7: -15, 8: -20, 9: -25, 10: -30, 11: -35, 12: -40}
CONCEPT = {"channel": "online", "logit_shift": 1.3, "from_month": DRIFT_MONTH}


def _month(m: int) -> tuple[date, date]:
    """First and last day of stream month m (1 = 2025-01)."""
    y, mo = STREAM_START[0] + (STREAM_START[1] - 1 + m - 1) // 12, (STREAM_START[1] - 1 + m - 1) % 12 + 1
    return date(y, mo, 1), date(y, mo, calendar.monthrange(y, mo)[1])


def label_delivery(m: int) -> date:
    """The day month m's labels arrive: the last day of month m + 3."""
    return _month(m + LABEL_LAG_MONTHS)[1]


def _draw(rng: np.random.Generator, n: int, dates: np.ndarray, month: int | None) -> pd.DataFrame:
    """n applications; `month` (1…12) is the stream month (None for the training book)."""
    dti_shift = DTI_SHIFT.get(month or 0, 0.0)
    score_shift = SCORE_SHIFT.get(month or 0, 0)
    age = rng.integers(21, 71, size=n)
    income = np.round(np.exp(rng.normal(10.9, 0.45, size=n)), -2)
    credit_score = np.clip(rng.normal(690 + score_shift, 60, size=n), 450, 850).round().astype(int)
    dti = np.round(np.clip(rng.beta(2.2, 5.0, size=n) + dti_shift, 0.01, 0.98), 3)
    util = np.round(np.clip(rng.beta(2.0, 3.6, size=n), 0.0, 1.0), 3)
    channel = rng.choice(CHANNELS, size=n, p=CHANNEL_P)
    employment = rng.choice(["salaried", "self-employed", "contract", "unemployed"], size=n, p=[0.62, 0.18, 0.13, 0.07])
    term = rng.choice([12, 24, 36, 48, 60], size=n, p=[0.1, 0.2, 0.35, 0.2, 0.15])
    amount = np.round(np.clip(income * rng.uniform(0.05, 0.4, size=n), 1_000, None), -2)
    prior = rng.poisson(0.35, size=n)
    c = COEFS
    logit = (c["intercept"] + c["credit_score_per_100"] * (credit_score - 690) / 100 + c["debt_to_income"] * (dti - 0.30)
             + c["utilization"] * (util - 0.35) + c["prior_defaults"] * prior
             + c["employment=unemployed"] * (employment == "unemployed")
             + c["employment=self-employed"] * (employment == "self-employed") + c["term_months_per_12"] * (term - 36) / 12)
    if month is not None and month >= CONCEPT["from_month"]:
        logit = logit + CONCEPT["logit_shift"] * (channel == CONCEPT["channel"])
    p = 1 / (1 + np.exp(-logit))
    y = (rng.random(n) < p).astype(int)
    return pd.DataFrame({
        "application_date": [d.isoformat() for d in dates],
        "age": age, "income_usd": income, "credit_score": credit_score, "debt_to_income": dti, "utilization": util,
        "channel": channel, "employment": employment, "term_months": term, "loan_amount_usd": amount,
        "prior_defaults": prior, "defaulted": y, "_p_true": p,
    })


def _dates(rng: np.random.Generator, start: date, end: date, n: int) -> np.ndarray:
    days = (end - start).days + 1
    return np.array(sorted(start + timedelta(days=int(d)) for d in rng.integers(0, days, size=n)))


def generate_loan_stream(n: int = N_TRAIN, seed: int = 42) -> tuple[pd.DataFrame, dict[str, Any]]:
    rng = np.random.default_rng(seed + 18)
    df = _draw(rng, n, _dates(rng, TRAIN_START, date(2024, 12, 31), n), None)
    df.insert(0, "application_id", [f"L-{500000 + i}" for i in range(n)])
    df = df.drop(columns=["_p_true"])
    months = []
    for m in range(1, 13):
        a, b = _month(m)
        months.append({"month": m, "label": a.strftime("%Y-%m"), "start": a.isoformat(), "end": b.isoformat(),
                       "rows": N_MONTH, "labels_arrive": label_delivery(m).isoformat(),
                       "covariate_drift": {"debt_to_income": DTI_SHIFT.get(m, 0.0), "credit_score": SCORE_SHIFT.get(m, 0)},
                       "concept_change": m >= CONCEPT["from_month"]})
    sidecar = {
        "dataset": "loan-stream", "seed": seed, "rows": n, "label_column": "defaulted", "problem_type": "binary",
        "id_column": "application_id", "date_column": "application_date",
        "signal": "logit P(default) = intercept + Σ coef · feature", "coefficients": COEFS,
        "stream": {"months": months, "rows_per_month": N_MONTH, "drift_month": DRIFT_MONTH,
                   "label_lag_months": LABEL_LAG_MONTHS,
                   "label_rule": "labels of month m arrive on the last day of month m + 3 (90 days past due)",
                   "covariate_drift": {"features": ["debt_to_income", "credit_score"],
                                       "debt_to_income": "Beta(2.2, 5.0) + δ_m", "credit_score": "N(690 + Δ_m, 60)",
                                       "delta_dti": DTI_SHIFT, "delta_score": SCORE_SHIFT,
                                       "seen_by": ["PSI per feature", "adversarial AUC (F15)", "score distribution"]},
                   "concept_change": {**CONCEPT, "description": "online applications default more for the same features "
                                                                "(logit + 1.3); the channel mix is unchanged",
                                      "seen_by": ["performance on labelled rows, from the end of month 10"],
                                      "not_seen_by": ["PSI", "adversarial AUC"]}},
    }
    return df, sidecar


def stream_month(m: int, seed: int = 42) -> tuple[pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    """(batch, labels, info) of stream month m (1…12). The batch has no label; the labels file has application_id,
    defaulted and label_date. Rows of month m are seeded by (seed, m) only."""
    if not 1 <= m <= 12:
        raise ValueError("The stream has months 1 to 12.")
    rng = np.random.default_rng([seed + 18, m])
    a, b = _month(m)
    df = _draw(rng, N_MONTH, _dates(rng, a, b, N_MONTH), m)
    ids = [f"L-{700000 + m * 10_000 + i}" for i in range(N_MONTH)]
    df.insert(0, "application_id", ids)
    labels = pd.DataFrame({"application_id": ids, "defaulted": df["defaulted"].to_numpy(),
                           "label_date": label_delivery(m).isoformat()})
    info = {"month": m, "label": a.strftime("%Y-%m"), "start": a.isoformat(), "end": b.isoformat(),
            "labels_arrive": label_delivery(m).isoformat(), "rows": N_MONTH,
            "default_rate": float(df["defaulted"].mean()), "mean_p_true": float(df["_p_true"].mean()),
            "covariate_drift": {"debt_to_income": DTI_SHIFT.get(m, 0.0), "credit_score": SCORE_SHIFT.get(m, 0)},
            "concept_change": m >= CONCEPT["from_month"]}
    return df.drop(columns=["defaulted", "_p_true"]), labels, info
