"""P23 (B5): the Postgres dialect behind `Database.connect()`.

The app's SQL is written once, in the SQLite dialect it grew up with (`?` and `:name` parameters, `INSERT OR IGNORE`,
`IS NOT x`, two-argument MIN/MAX, `PRAGMA table_info`, `BEGIN IMMEDIATE`). On Postgres each statement goes through
`translate()` (cached per statement text), and the connection hands out rows that read like `sqlite3.Row` (by index and
by name, `keys()`, `dict(row)`). What cannot be translated by rule was made portable at its call site instead (see
docs/progress/P23.md for the grep list).

- Connections come from one `psycopg_pool.ConnectionPool` per (process, URL). A forked child builds its own.
- A `with db.connect()` block is one transaction: committed at the end, rolled back on an exception (as on SQLite).
- `BEGIN IMMEDIATE` (SQLite's "take the write lock now") becomes a transaction advisory lock on one key, so the few
  writers that relied on SQLite's single writer (the version writer, split restore, the lake migration) still serialise.
- psycopg errors are re-raised as the matching `sqlite3` exception class (`IntegrityError` for constraint and trigger
  violations, `OperationalError` otherwise), so the existing `except sqlite3.…` handlers keep working. The original
  error is chained (`__cause__`).
- Credentials are never stored: the URL is read from the environment (`ENSEMBLE_DB_URL`) on every start."""

from __future__ import annotations

import os
import re
import sqlite3
import threading
from contextlib import contextmanager
from decimal import Decimal
from functools import lru_cache
from typing import Any, Iterator

#: the key of the advisory lock `BEGIN IMMEDIATE` maps to (any constant; "ENSW" as an int)
WRITE_LOCK_KEY = 0x454E5357


def env_url() -> str | None:
    """The metadata DB URL from the environment, or None for SQLite (the default, and local dev)."""
    v = (os.environ.get("ENSEMBLE_DB_URL") or os.environ.get("ENSEMBLE_DATABASE_URL") or "").strip()
    return v or None


def is_pg_url(url: str | None) -> bool:
    return bool(url) and url.split(":", 1)[0] in ("postgres", "postgresql", "postgresql+psycopg")


def redact(url: str) -> str:
    """A URL safe to log: the password replaced."""
    return re.sub(r"(//[^:/@]+:)[^@]*@", r"\1***@", url)


# ---------------------------------------------------------------------------------------------------------- translate

_LIT = re.compile(r"'(?:[^']|'')*'|\"(?:[^\"]|\"\")*\"|--[^\n]*")
_PK = {  # INSERT OR REPLACE needs the conflict target on Postgres
    "catalog_meta": ("key",),
    "table_stats": ("table_sha256",),
    "diff_cache": ("a_sha256", "b_sha256", "key"),
}
_TYPES = [
    (re.compile(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", re.I), "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
    (re.compile(r"\bINTEGER\b", re.I), "BIGINT"),
    (re.compile(r"\bREAL\b", re.I), "DOUBLE PRECISION"),
    (re.compile(r"\bBLOB\b", re.I), "BYTEA"),
]


def _mask(sql: str) -> tuple[str, list[str]]:
    lits: list[str] = []

    def keep(m: re.Match) -> str:
        if m.group(0).startswith("--"):
            return " "
        lits.append(m.group(0))
        return f"\x00{len(lits) - 1}\x00"

    return _LIT.sub(keep, sql), lits


def _unmask(code: str, lits: list[str], escape_pct: bool) -> str:
    def put(m: re.Match) -> str:
        s = lits[int(m.group(1))]
        return s.replace("%", "%%") if escape_pct else s

    return re.sub(r"\x00(\d+)\x00", put, code)


def _scalar_minmax(code: str) -> str:
    """SQLite's two-argument MIN(a, b) / MAX(a, b) are LEAST / GREATEST on Postgres (aggregates keep one argument)."""
    out, i = [], 0
    for m in re.finditer(r"\b(MIN|MAX)\s*\(", code, re.I):
        if m.start() < i:
            continue
        depth, j, comma = 1, m.end(), False
        while j < len(code) and depth:
            c = code[j]
            depth += c == "("
            depth -= c == ")"
            comma |= c == "," and depth == 1
            j += 1
        if comma:
            out.append(code[i:m.start()])
            out.append(("LEAST(" if m.group(1).upper() == "MIN" else "GREATEST(") + _scalar_minmax(code[m.end():j - 1]) + ")")
            i = j
    out.append(code[i:])
    return "".join(out)


def _pragma(code: str) -> str | None:
    m = re.match(r"\s*PRAGMA\s+(\w+)\s*(?:\(\s*\"?(\w+)\"?\s*\)|=\s*\w+)?\s*;?\s*$", code, re.I)
    if not m:
        return None
    if m.group(1).lower() == "table_info" and m.group(2):
        # the sqlite3 shape: cid, name, type, notnull, dflt_value, pk
        return ("SELECT c.ordinal_position - 1 AS cid, c.column_name AS name, upper(c.data_type) AS type,"
                " CASE WHEN c.is_nullable = 'NO' THEN 1 ELSE 0 END AS notnull, c.column_default AS dflt_value, 0 AS pk"
                f" FROM information_schema.columns c WHERE c.table_schema = current_schema() AND c.table_name = '{m.group(2).lower()}'"
                " ORDER BY c.ordinal_position")
    return "SELECT 1 WHERE FALSE"  # journal_mode, foreign_keys, synchronous, busy_timeout: nothing to do on Postgres


@lru_cache(maxsize=4096)
def translate(sql: str, params: bool = True) -> str:
    """One SQLite-dialect statement → Postgres. `params`: the statement is sent with parameters, so `%` is escaped."""
    if re.match(r"\s*(CREATE|DROP)\s+TRIGGER\b", sql, re.I):
        from .catalog.pg_schema import trigger_sql

        return trigger_sql(sql)
    code, lits = _mask(sql)
    p = _pragma(code)
    if p is not None:
        return p
    if re.fullmatch(r"\s*BEGIN\s+(IMMEDIATE|EXCLUSIVE)\s*;?\s*", code, re.I):
        return f"SELECT pg_advisory_xact_lock({WRITE_LOCK_KEY})"
    if re.fullmatch(r"\s*BEGIN(\s+DEFERRED|\s+TRANSACTION)?\s*;?\s*", code, re.I):
        return "SELECT 1 WHERE FALSE"  # psycopg has already opened the transaction
    if params:
        code = code.replace("%", "%%")
    # INSERT OR IGNORE / OR REPLACE → ON CONFLICT
    m = re.match(r"(\s*)INSERT\s+OR\s+(IGNORE|REPLACE)\s+INTO\s+(\w+)\s*(\(([^)]*)\))?", code, re.I)
    if m:
        table, how = m.group(3), m.group(2).upper()
        code = f"{m.group(1)}INSERT INTO {table} " + code[m.end(3):].lstrip()
        if how == "IGNORE":
            tail = " ON CONFLICT DO NOTHING"
        else:
            pk = _PK.get(table.lower())
            cols = [c.strip() for c in (m.group(5) or "").split(",") if c.strip()]
            if not pk or not cols:
                raise ValueError(f"INSERT OR REPLACE INTO {table}: add its key to db_pg._PK")
            sets = ", ".join(f"{c} = EXCLUDED.{c}" for c in cols if c not in pk)
            tail = f" ON CONFLICT ({', '.join(pk)}) " + (f"DO UPDATE SET {sets}" if sets else "DO NOTHING")
        r = re.search(r"\sRETURNING\s", code, re.I)
        code = code.rstrip().rstrip(";")
        code = (code[:r.start()] + tail + code[r.start():]) if r else code + tail
    # ON CONFLICT … DO UPDATE SET c = f(c): a bare column on the right means the existing row; Postgres needs it qualified
    m = re.match(r"\s*INSERT\s+INTO\s+(\w+)\s*\(([^)]*)\)", code, re.I)
    u = re.search(r"\bDO\s+UPDATE\s+SET\b", code, re.I)
    if m and u:
        table, cols = m.group(1), [c.strip() for c in m.group(2).split(",") if c.strip()]
        tail = code[u.end():]
        for c in cols:
            tail = re.sub(rf"(?<![.\w\x00]){c}\b(?!\s*=(?!=))", f"{table}.{c}", tail)
        code = code[:u.end()] + tail
    # IS / IS NOT with a value (not NULL/TRUE/FALSE): IS [NOT] DISTINCT FROM
    code = re.sub(r"\bIS\s+NOT\s+(?!NULL\b|DISTINCT\b|TRUE\b|FALSE\b)", "IS DISTINCT FROM ", code, flags=re.I)
    code = re.sub(r"\bIS\s+(?!NOT\b|NULL\b|DISTINCT\b|TRUE\b|FALSE\b)", "IS NOT DISTINCT FROM ", code, flags=re.I)
    code = _scalar_minmax(code)
    code = re.sub(r"\bLIKE\b", "ILIKE", code, flags=re.I)  # SQLite's LIKE ignores ASCII case
    code = re.sub(r"\bIN\s*\(\s*\)", "IN (NULL)", code, flags=re.I)
    # a mixed-case alias keeps its case (Postgres folds unquoted names)
    code = re.sub(r"\bAS\s+([A-Za-z_]\w*)\b", lambda m: f'AS "{m.group(1)}"' if (m.group(1) != m.group(1).lower()
                  and m.group(1) != m.group(1).upper()) else m.group(0), code)
    if re.match(r"\s*(CREATE|ALTER)\s", code, re.I) or re.search(r"\bCAST\s*\(", code, re.I):
        for rx, to in _TYPES:
            code = rx.sub(to, code)
    if params:
        code = re.sub(r"\?", "%s", code)
        code = re.sub(r"(?<![:\w]):([A-Za-z_]\w*)", r"%(\1)s", code)
    return _unmask(code, lits, params)


def split_script(script: str) -> list[str]:
    """Statements of a script (`;` outside literals and comments)."""
    code, lits = _mask(script)
    return [_unmask(s, lits, False).strip() for s in code.split(";") if s.strip()]


# ----------------------------------------------------------------------------------------------------------------- rows

class Row(tuple):
    """A result row that reads like sqlite3.Row: r[0], r["name"], keys(), dict(r)."""

    __slots__ = ()
    _names: tuple[str, ...] = ()
    _index: dict[str, int] = {}

    def __getitem__(self, k):  # type: ignore[override]
        if isinstance(k, str):
            i = self._index.get(k)
            if i is None:
                i = self._index.get(k.lower())
                if i is None:
                    raise IndexError(f"No item with that key: {k}")
            return tuple.__getitem__(self, i)
        return tuple.__getitem__(self, k)

    def keys(self) -> list[str]:
        return list(self._names)

    def get(self, k: str, default: Any = None) -> Any:
        try:
            return self[k]
        except IndexError:
            return default


def _row_factory(cursor):
    desc = cursor.description
    if desc is None:
        return tuple
    names = tuple(c.name for c in desc)
    index: dict[str, int] = {}
    for i, n in enumerate(names):
        index.setdefault(n, i)
        index.setdefault(n.lower(), i)
    cls = type("Row", (Row,), {"__slots__": (), "_names": names, "_index": index})
    return lambda values: cls(values)


def _fix(params: Any) -> Any:
    """bool → 0/1 (the columns are INTEGER 0/1, as on SQLite)."""
    if params is None:
        return ()
    if isinstance(params, dict):
        return {k: int(v) if isinstance(v, bool) else v for k, v in params.items()}
    return [int(v) if isinstance(v, bool) else v for v in params]


def _wrap(e: Exception) -> Exception:
    import psycopg

    msg = str(e).strip().splitlines()[0] if str(e).strip() else type(e).__name__
    if isinstance(e, psycopg.errors.IntegrityError) or (isinstance(e, psycopg.errors.RaiseException)):
        out: Exception = sqlite3.IntegrityError(msg)
    else:
        out = sqlite3.OperationalError(msg)
    out.pg_error = e  # type: ignore[attr-defined]
    return out


# ----------------------------------------------------------------------------------------------------------- connection

class PgConnection:
    """The subset of sqlite3.Connection the app uses, over one pooled psycopg connection."""

    dialect = "postgres"

    def __init__(self, raw) -> None:
        self.raw = raw

    def _cur(self):
        return self.raw.cursor(row_factory=_row_factory)

    def execute(self, sql: str, params: Any = None):
        has = params is not None and len(params) > 0
        q = translate(sql, has)
        cur = self._cur()
        try:
            cur.execute(q, _fix(params) if has else None)
        except Exception as e:  # noqa: BLE001
            import psycopg

            if isinstance(e, psycopg.Error):
                raise _wrap(e) from e
            raise
        return cur

    def executemany(self, sql: str, seq: Any):
        q = translate(sql, True)
        cur = self._cur()
        try:
            cur.executemany(q, [_fix(p) for p in seq])
        except Exception as e:  # noqa: BLE001
            import psycopg

            if isinstance(e, psycopg.Error):
                raise _wrap(e) from e
            raise
        return cur

    def executescript(self, script: str) -> None:
        for s in split_script(script):
            self.execute(s)

    def commit(self) -> None:
        self.raw.commit()

    def rollback(self) -> None:
        self.raw.rollback()

    def close(self) -> None:  # returned to the pool by Database.connect()
        pass

    @property
    def in_transaction(self) -> bool:
        from psycopg.pq import TransactionStatus

        return self.raw.info.transaction_status != TransactionStatus.IDLE

    def __enter__(self):
        return self

    def __exit__(self, *a) -> None:
        pass


def _configure(conn) -> None:
    from psycopg.adapt import Loader

    class Num(Loader):
        """numeric (SUM of bigint, AVG) → int when whole, else float: what sqlite3 returns."""

        def load(self, data):
            d = Decimal(bytes(data).decode())
            return int(d) if d == d.to_integral_value() and abs(d) < (1 << 63) else float(d)

    conn.adapters.register_loader("numeric", Num)


_pools: dict[tuple[int, str], Any] = {}
_pools_lock = threading.Lock()


def pool(url: str):
    from psycopg_pool import ConnectionPool

    k = (os.getpid(), url)
    p = _pools.get(k)
    if p is None:
        with _pools_lock:
            p = _pools.get(k)
            if p is None:
                p = ConnectionPool(url, min_size=int(os.environ.get("ENSEMBLE_DB_POOL_MIN", "1")),
                                   max_size=int(os.environ.get("ENSEMBLE_DB_POOL_MAX", "20")),
                                   timeout=float(os.environ.get("ENSEMBLE_DB_POOL_TIMEOUT_S", "30")),
                                   configure=_configure, kwargs={"autocommit": False}, open=True,
                                   name=f"ensemble-{os.getpid()}")
                _pools[k] = p
    return p


@contextmanager
def connect(url: str) -> Iterator[PgConnection]:
    with pool(url).connection() as raw:
        con = PgConnection(raw)
        try:
            yield con
            raw.commit()
        except BaseException:
            raw.rollback()
            raise


class _Borrowed(PgConnection):
    """A pooled connection handed out without a `with` block (lake/pages.meta_con): close() rolls back and returns it."""

    def __init__(self, url: str) -> None:
        self._pool = pool(url)
        super().__init__(self._pool.getconn())

    def close(self) -> None:
        if self.raw is not None:
            try:
                self.raw.rollback()
            finally:
                self._pool.putconn(self.raw)
                self.raw = None


def borrow(url: str) -> PgConnection:
    return _Borrowed(url)


@contextmanager
def direct(url: str, autocommit: bool = False) -> Iterator[PgConnection]:
    """One unpooled connection (migrations as the owner role, the copy tool)."""
    import psycopg

    raw = psycopg.connect(url, autocommit=autocommit)
    _configure(raw)
    try:
        con = PgConnection(raw)
        yield con
        if not autocommit:
            raw.commit()
    except BaseException:
        if not autocommit:
            raw.rollback()
        raise
    finally:
        raw.close()
