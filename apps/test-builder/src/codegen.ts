// Turns the successful steps of an exploration into a readable Playwright Test file.
import { locatorCode, quote, describeAction, type Action } from './actions.ts';
import type { PolicyBlock } from './policy.ts';

export interface CodegenInput {
  goal: string;
  planner: string;
  targetName: string;
  targetPath: string;
  steps: Action[];
  blocks: PolicyBlock[];
  credentialKeys: string[];
  fixturesImport: string;
  generatedAt: string;
}

/** "{{password}}" -> secret('password'); anything else -> a string literal. */
function valueCode(v: string, keys: string[]): string {
  const totpM = /^\{\{totp:(\w+)\}\}$/.exec(v);
  if (totpM && keys.includes(totpM[1]!)) return `totp(secret(${quote(totpM[1]!)}))`;
  const m = /^\{\{(\w+)\}\}$/.exec(v);
  if (m && keys.includes(m[1]!)) return `secret(${quote(m[1]!)})`;
  if (/\{\{\w+\}\}/.test(v)) {
    const tpl = v.replace(/[`\\$]/g, '\\$&')
      .replace(/\{\{totp:(\w+)\}\}/g, (all, k: string) => (keys.includes(k) ? `\${totp(secret('${k}'))}` : all))
      .replace(/\{\{(\w+)\}\}/g, (all, k: string) => (keys.includes(k) ? `\${secret('${k}')}` : all));
    return '`' + tpl + '`';
  }
  return quote(v);
}

function stepCode(a: Action, keys: string[]): string | null {
  switch (a.action) {
    case 'goto': return `await page.goto(${quote(a.url)});`;
    case 'click': return `await ${locatorCode(a.target)}.click();`;
    case 'fill': return `await ${locatorCode(a.target)}.fill(${valueCode(a.value, keys)});`;
    case 'select': return `await ${locatorCode(a.target)}.selectOption({ label: ${quote(a.option)} });`;
    case 'press': return a.target ? `await ${locatorCode(a.target)}.press(${quote(a.key)});` : `await page.keyboard.press(${quote(a.key)});`;
    case 'hover': return `await ${locatorCode(a.target)}.hover();`;
    case 'upload': return `await ${locatorCode(a.target)}.setInputFiles(filePath(${quote(a.file)}));`;
    case 'otp': {
      const scope = a.within ? locatorCode(a.within) : 'page';
      return `await enterOtp(${scope}.getByRole('textbox'), ${valueCode(a.value, keys)});`;
    }
    case 'waitFor': return `await ${locatorCode(a.target)}.waitFor({ state: ${quote(a.state ?? 'visible')} });`;
    case 'download': return a.contains?.length
      ? `await expectDownload(page, ${locatorCode(a.target)}, ${JSON.stringify(a.contains)});`
      : `await expectDownload(page, ${locatorCode(a.target)});`;
    case 'expectVisible': return `await expect(${locatorCode(a.target)}).toBeVisible();`;
    case 'expectText': return `await expect(${locatorCode(a.target)}).toContainText(${quote(a.text)});`;
    case 'expectCount': return `await expect(${locatorCode(a.target)}).toHaveCount(${a.count});`;
    case 'done': return null;
  }
}

export function generateSpec(i: CodegenInput): string {
  const groups: { title: string; lines: string[] }[] = [];
  let n = 0;
  for (const a of i.steps) {
    const code = stepCode(a, i.credentialKeys);
    if (!code) continue;
    const title = ('group' in a && a.group) || `Step ${++n}`;
    const last = groups.at(-1);
    if (last && last.title === title) last.lines.push(code);
    else groups.push({ title, lines: [code] });
  }
  const assertions = i.steps.filter((s) => s.action.startsWith('expect')).length;
  const blockLines = i.blocks.map((b) => b.kind === 'action'
    ? `//   - ${b.action} ${b.role} "${b.name}"  [forbiddenActions ${b.rule}]`
    : `//   - ${b.method} ${b.url}  [${b.reason}${b.rule ? ` ${b.rule}` : ''}]`);
  const header = [
    `// Generated by test-builder explore at ${i.generatedAt}`,
    `// Goal:    ${i.goal}`,
    `// Planner: ${i.planner}`,
    `// Target:  ${i.targetName} (${i.targetPath})`,
    `// Steps:   ${i.steps.length} recorded, ${assertions} assertion(s)`,
    ...(blockLines.length ? ['// Blocked by policy during exploration (excluded from this test):', ...blockLines] : []),
    '// Credentials are read from env at run time via secret(); no values are stored in this file.',
  ];
  if (assertions === 0) header.push('// WARNING: the exploration produced no assertions; this test only proves the steps do not throw.');
  const body = groups.map((g) => [
    `  await test.step(${quote(g.title)}, async () => {`,
    ...g.lines.map((l) => `    ${l}`),
    '  });',
  ].join('\n')).join('\n\n');
  const helpers = [
    ['totp(', 'totp'], ['secret(', 'secret'], ['filePath(', 'filePath'], ['enterOtp(', 'enterOtp'], ['expectDownload(', 'expectDownload'],
  ].filter(([needle]) => body.includes(needle!)).map(([, name]) => name!);
  const imports = ['test', ...(body.includes('expect(') ? ['expect'] : []), ...helpers];
  return `${header.join('\n')}
import { ${imports.join(', ')} } from ${quote(i.fixturesImport)};

test(${quote(i.goal)}, async ({ page }) => {
${body}
});
`;
}

export { describeAction };
