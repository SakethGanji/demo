-- Project datasets: a project's link to a file stored by the analytics service (CSV, Parquet, XLSX, XLS). The bytes
-- and versions live there; this row carries the id workflows store (a node's datasetId is project_datasets.id), the
-- name people see and a copy of the shape for listing without a round trip. Additive; sorts after
-- 20261022120000_capability_graph.
--
-- Cross-database contract: project_datasets.dataset_id <-> analytics datasets.id, and project_datasets.version_id <->
-- analytics dataset_versions.id (the version imported). The two services keep separate Postgres databases for now, so
-- there is NO foreign key on either column: the engine keeps them in step (upload compensation, delete-analytics-first)
-- and reports drift as `missing`. When the databases merge, both become real foreign keys.

-- migrate:up
SET search_path TO "workflow-app";

CREATE TABLE IF NOT EXISTS project_datasets (
  id            UUID PRIMARY KEY,                     -- UUIDv7, generated by the engine; what workflows store
  team_id       TEXT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  project_id    TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  dataset_id    UUID NOT NULL,                        -- analytics datasets.id (no FK while the databases are separate)
  version_id    UUID,                                 -- analytics dataset_versions.id imported (no FK, same reason)
  name          TEXT NOT NULL,
  file_name     TEXT NOT NULL,
  format        TEXT NOT NULL CHECK (format IN ('csv','parquet','xlsx','xls')),
  row_count     INTEGER,
  column_count  INTEGER,
  size_bytes    BIGINT,
  columns       JSONB NOT NULL DEFAULT '[]'::jsonb,   -- [{name, type}] in file order
  created_by    TEXT,
  created_at    TIMESTAMP NOT NULL DEFAULT now(),
  updated_at    TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_project_datasets_team_id ON project_datasets (team_id);
CREATE INDEX IF NOT EXISTS ix_project_datasets_project_id ON project_datasets (project_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_project_datasets_project_name ON project_datasets (project_id, name);
CREATE UNIQUE INDEX IF NOT EXISTS ux_project_datasets_project_dataset ON project_datasets (project_id, dataset_id);

