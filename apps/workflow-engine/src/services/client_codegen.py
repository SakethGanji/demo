"""Generate the typed TypeScript client for a project's API (BACKEND-DESIGN §3.6, G18, G19).

* Only ``none`` and ``app_token`` routes are emitted — ``api_key`` routes never reach browser code.
* The header is an esbuild-preserved legal comment carrying the spec revision and hash.
* Lives at ``api/client.ts`` in app files; publish and the AI working set overwrite it.
"""

from __future__ import annotations

import json
import re
from typing import Any

from .spec_tools import PARAM_RE

CLIENT_PATH = "api/client.ts"


def _ts_type(schema: Any, depth: int = 0) -> str:
    if not isinstance(schema, dict) or not schema or depth > 8:
        return "any"
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(sorted({_ts_type({**schema, "type": x}, depth) for x in t}))
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if t == "string":
        return "string"
    if t in ("number", "integer"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        return f"Array<{_ts_type(schema.get('items'), depth + 1)}>"
    if t == "object" or "properties" in schema:
        props = schema.get("properties") or {}
        if not props:
            return "Record<string, any>"
        req = set(schema.get("required") or [])
        fields = []
        for k, v in props.items():
            key = k if re.match(r"^[A-Za-z_$][A-Za-z0-9_$]*$", k) else json.dumps(k)
            fields.append(f"{key}{'' if k in req else '?'}: {_ts_type(v, depth + 1)}")
        return "{ " + "; ".join(fields) + " }"
    return "any"


def _pascal(name: str) -> str:
    return name[:1].upper() + name[1:]


def generate_client(slug: str, routes: list[dict[str, Any]], revision: int | None, spec_hash_: str) -> str:
    lines = [
        f"/*! @generated by studio — spec rev {revision if revision is not None else 'draft'}, spec_hash {spec_hash_} — do not edit */",
        "// Typed client for this project's API. Import it as `import { api } from './api/client'`.",
        "",
        "export class ApiError extends Error {",
        "  constructor(public status: number, public body: unknown) { super(`HTTP ${status}`) }",
        "}",
        "",
        f"export const BASE = '/api/p/{slug}'",
        "",
        "function qs(query?: Record<string, unknown>): string {",
        "  if (!query) return ''",
        "  const parts: string[] = []",
        "  for (const [k, v] of Object.entries(query)) {",
        "    if (v === undefined || v === null) continue",
        "    parts.push(encodeURIComponent(k) + '=' + encodeURIComponent(String(v)))",
        "  }",
        "  return parts.length ? '?' + parts.join('&') : ''",
        "}",
        "",
        "async function send(method: string, path: string, opts: { query?: Record<string, unknown>; body?: unknown }): Promise<Response> {",
        "  const token = (window as any).__APP_TOKEN",
        "  const headers: Record<string, string> = { 'Content-Type': 'application/json' }",
        "  if (token) headers['Authorization'] = `Bearer ${token}`",
        "  return fetch(BASE + path + qs(opts.query), {",
        "    method, headers, body: opts.body === undefined ? undefined : JSON.stringify(opts.body),",
        "  })",
        "}",
        "",
        "async function call<T>(method: string, path: string, opts: { query?: Record<string, unknown>; body?: unknown } = {}): Promise<T> {",
        "  let res = await send(method, path, opts)",
        "  // Expired page token: refresh once (window.__APP_REFRESH, set by the published runtime / preview) and retry.",
        "  const refresh = (window as any).__APP_REFRESH",
        "  if (res.status === 401 && typeof refresh === 'function') {",
        "    if (await refresh()) res = await send(method, path, opts)",
        "  }",
        "  const ct = res.headers.get('content-type') || ''",
        "  const data = ct.includes('json') ? await res.json() : await res.text()",
        "  if (!res.ok) throw new ApiError(res.status, data)",
        "  return data as T",
        "}",
        "",
    ]
    ops = []
    for r in sorted(routes, key=lambda x: x["name"]):
        if r.get("auth") == "api_key":
            continue
        name = r["name"]
        P = _pascal(name)
        params = PARAM_RE.findall(r["path"])
        req = r.get("request_schema") or {}
        props = req.get("properties") or {}
        has_body = "body" in props or r["method"] in ("POST", "PUT", "PATCH")
        lines.append(f"export type {P}Response = {_ts_type(r.get('response_schema'))}")
        if "body" in props:
            lines.append(f"export type {P}Body = {_ts_type(props['body'])}")
        path_expr = "`" + PARAM_RE.sub(lambda m: "${encodeURIComponent(String(params." + m.group(1) + "))}", r["path"]) + "`"
        args = []
        if params:
            args.append("params: { " + "; ".join(f"{p}: string | number" for p in params) + " }")
        if has_body:
            args.append(f"body?: {P}Body" if "body" in props else "body?: unknown")
        args.append(f"query?: {_ts_type(props.get('query')) if props.get('query') else 'Record<string, unknown>'}")
        call_opts = "{ query" + (", body" if has_body else "") + " }"
        doc = (r.get("description") or "").replace("*/", "")
        ops.append(f"  /** {r['method']} {r['path']}{(' — ' + doc) if doc else ''} */")
        ops.append(f"  {name}: ({', '.join(args)}): Promise<{P}Response> => call<{P}Response>('{r['method']}', {path_expr}, {call_opts}),")
    lines.append("")
    lines.append("export const api = {")
    lines.extend(ops)
    lines.append("}")
    lines.append("")
    lines.append("export default api")
    lines.append("")
    return "\n".join(lines)
