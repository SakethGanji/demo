"""The typed TypeScript client of a workflow interface (Stage 5, DESIGN-STAGE5-UIS section 6.3 'Typed client').

``generate_interface_client(definition, interface, project_slug, shapes_by_node=None) -> str`` is pure and
deterministic (same input, same bytes), so it can be snapshot-tested and type-checked with ``tsc --noEmit``.

The module gives an app the four verbs of the brief: ``startRun``, ``watchRun`` (polling with backoff, no SSE),
``listTasks`` and ``approveTask`` / ``rejectTask``. Types come from the contracts: the trigger's ``input_schema``,
the result node's body and each Approval node's ``form``.
"""

from __future__ import annotations

import json
import re
from typing import Any

from ..engine import shapes as sh
from .client_codegen import _ts_type

_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def pascal(text: str) -> str:
    """``refund-triage`` / ``Manager review`` -> ``RefundTriage`` / ``ManagerReview`` (never empty, never starts with a digit)."""
    out = "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", text or "") if w)
    if not out:
        return "Workflow"
    return out if not out[0].isdigit() else "N" + out


def _key(name: str) -> str:
    return name if _IDENT.match(name) else json.dumps(name)


def _field_type(field: dict[str, Any]) -> str:
    t = field.get("type")
    if t == "number":
        return "number"
    if t == "checkbox":
        return "boolean"
    if t == "select" and isinstance(field.get("options"), list) and field["options"]:
        opts = [o.get("value", o) if isinstance(o, dict) else o for o in field["options"]]
        return " | ".join(json.dumps(str(o)) for o in opts)
    return "string"


def form_data_type(form: Any) -> str:
    """The TS type of an Approval node's ``form_data`` from its ``form`` (FieldSpec list)."""
    fields = [f for f in (form if isinstance(form, list) else []) if isinstance(f, dict) and f.get("name")]
    if not fields:
        return "Record<string, never>"
    parts = [f"{_key(str(f['name']))}{'' if f.get('required') else '?'}: {_field_type(f)}" for f in fields]
    return "{ " + "; ".join(parts) + " }"


def _result_type(definition: dict[str, Any], interface: dict[str, Any], shapes_by_node: dict[str, Any] | None) -> str:
    node = next((n for n in definition.get("nodes") or [] if n.get("name") == interface.get("result_node")), None)
    if node is None:
        return "Record<string, unknown>"
    body = (node.get("parameters") or {}).get("body", "{{ $json }}")
    if isinstance(body, str):
        try:
            body = json.loads(body)
        except ValueError:
            pass
    in_shape = (((shapes_by_node or {}).get(node["name"]) or {}).get("inputs") or {}).get("main") or sh.unknown()
    if isinstance(body, dict) and body:
        props: dict[str, Any] = {}
        for k, v in body.items():
            props[str(k)] = sh.expression_value_shape(v, in_shape) if isinstance(v, str) and "{{" in v else sh.from_value(v)
        shape = sh.object_of(props, [], "derived")
        return _unknown(_ts_type(shape)) if props else "Record<string, unknown>"
    if isinstance(body, str) and body.strip().replace(" ", "") == "{{$json}}":
        return _unknown(_ts_type(in_shape)) if not sh.is_unknown(in_shape) else "Record<string, unknown>"
    return "unknown"


def _unknown(ts: str) -> str:
    """``any`` (what ``_ts_type`` says for an unknown shape) -> ``unknown`` (never inside a name or a string literal)."""
    return re.sub(r'(?<![\w"\'])any(?![\w"\'])', "unknown", ts)


def generate_interface_client(definition: dict[str, Any], interface: dict[str, Any], project_slug: str,
                              workflow_id: str = "", project_id: str = "",
                              shapes_by_node: dict[str, Any] | None = None) -> str:
    slug = str(interface.get("slug") or "interface")
    P = pascal(slug)
    trigger = next((n for n in definition.get("nodes") or [] if n.get("name") == interface.get("trigger_node")), None)
    raw_schema = ((trigger or {}).get("parameters") or {}).get("input_schema")
    input_shape = sh.normalize(raw_schema, "declared") if raw_schema else sh.object_of({}, [], "declared")
    approvals = sorted((n for n in definition.get("nodes") or [] if n.get("type") == "Approval"), key=lambda n: n["name"])
    kind = interface.get("kind")

    L: list[str] = [
        f"/*! @generated by studio - interface {slug} of project {project_slug}{' (' + workflow_id + ')' if workflow_id else ''} - do not edit */",
        "// Typed client for this workflow's interface. Runs are polled (no streaming), so it works across reloads and restarts.",
        "",
        f"export interface {P}Input {_ts_type(input_shape) if input_shape.get('properties') else '{ [field: string]: unknown }'}",
        f"export type {P}Result = {_result_type(definition, interface, shapes_by_node)}",
        "",
    ]
    for n in approvals:
        L.append(f"export interface {pascal(n['name'])}Decision {{ comment?: string; form_data: {form_data_type((n.get('parameters') or {}).get('form'))} }}")
    if approvals:
        L.append("export type TaskNode = " + " | ".join(json.dumps(n["name"]) for n in approvals))
        L.append("export interface DecisionByNode { " + "; ".join(f"{json.dumps(n['name'])}: {pascal(n['name'])}Decision" for n in approvals) + " }")
    else:
        L.append("export type TaskNode = string")
        L.append("export interface DecisionByNode { [node: string]: { comment?: string; form_data?: Record<string, unknown> } }")
    L += [
        "",
        'export type RunStatus = "running" | "waiting" | "success" | "failed" | "cancelled"',
        "export interface TaskRef { task_id: string; title: string; due_at: string | null }",
        "export interface RunError { code: string; message: string }",
        "export interface RunView<R> {",
        "  execution_id: string",
        "  status: RunStatus",
        "  progress?: { done: number; total: number; current: string | null }",
        "  waiting_for: TaskRef[]",
        "  result: R | null",
        "  message: string | null",
        "  error: RunError | null",
        "}",
        "export interface TaskSummary {",
        "  id: string; workflow_id: string; workflow_name: string; execution_id: string; node_name: string; title: string",
        '  status: "open" | "approved" | "rejected" | "timed_out" | "cancelled"',
        "  assignees: string[]; due_at: string | null; created_at: string; decided_by: string | null; decided_at: string | null",
        "}",
        "export interface TaskDetail<N extends string = string> extends TaskSummary {",
        "  node_name: N",
        "  context: Record<string, unknown>; form: Array<Record<string, unknown>>; decision: Record<string, unknown> | null",
        "  screen: Record<string, unknown> | null; input: Record<string, unknown>; allow_comment: boolean",
        "  require_comment_on_reject: boolean; on_timeout: string; run_status: string",
        "}",
        'export interface DecideResult<N extends string = string> { task: TaskDetail<N>; outcome: "decided" | "already_decided" | "already_closed" }',
        "export interface Page<T> { items: T[]; next_cursor: string | null }",
        "export class InterfaceApiError extends Error {",
        "  constructor(public status: number, public body: unknown) { super(`HTTP ${status}`) }",
        "}",
        "",
        f"const PROJECT = {json.dumps(project_slug)}",
        f"const SLUG = {json.dumps(slug)}",
        f"const PROJECT_ID = {json.dumps(project_id)}",
        f"const WORKFLOW_ID = {json.dumps(workflow_id)}",
        "const TERMINAL: RunStatus[] = [\"success\", \"failed\", \"cancelled\"]",
        "",
        "export interface ClientOptions { fetch?: typeof fetch }",
        "",
        "export function createClient(baseUrl: string, opts: ClientOptions = {}) {",
        "  const base = baseUrl.replace(/\\/+$/, \"\")",
        "  const doFetch: typeof fetch = opts.fetch ?? ((input, init) => fetch(input, init))",
        "",
        "  async function call<T>(method: string, path: string, init: { body?: unknown; headers?: Record<string, string> } = {}): Promise<T> {",
        "    const headers: Record<string, string> = { Accept: \"application/json\", ...(init.headers ?? {}) }",
        "    if (init.body !== undefined) headers[\"Content-Type\"] = \"application/json\"",
        "    const res = await doFetch(base + path, { method, headers, body: init.body === undefined ? undefined : JSON.stringify(init.body) })",
        "    const type = res.headers.get(\"content-type\") ?? \"\"",
        "    const data: unknown = type.includes(\"json\") ? await res.json() : await res.text()",
        "    if (!res.ok) throw new InterfaceApiError(res.status, data)",
        "    return data as T",
        "  }",
        "",
        "  function newKey(): string {",
        "    const c = (globalThis as { crypto?: { randomUUID?: () => string } }).crypto",
        "    return c && c.randomUUID ? c.randomUUID() : `k-${Date.now()}-${Math.random().toString(36).slice(2)}`",
        "  }",
        "",
        "  const wait = (ms: number, signal?: AbortSignal) => new Promise<void>((resolve, reject) => {",
        "    if (signal && signal.aborted) { reject(new Error(\"aborted\")); return }",
        "    const t = setTimeout(resolve, ms)",
        "    if (signal) signal.addEventListener(\"abort\", () => { clearTimeout(t); reject(new Error(\"aborted\")) }, { once: true })",
        "  })",
        "",
        "  function qs(params: Record<string, string | number | undefined>): string {",
        "    const parts: string[] = []",
        "    for (const k of Object.keys(params)) {",
        "      const v = params[k]",
        "      if (v !== undefined && v !== \"\") parts.push(encodeURIComponent(k) + \"=\" + encodeURIComponent(String(v)))",
        "    }",
        "    return parts.length ? \"?\" + parts.join(\"&\") : \"\"",
        "  }",
        "",
        "  const root = `/api/i/${encodeURIComponent(PROJECT)}/${encodeURIComponent(SLUG)}`",
        "",
        "  return {",
    ]
    if kind in ("form", "custom"):
        L += [
            f"    /** Start a run. Retrying with the same idempotencyKey returns the same run. */",
            f"    startRun(input: {P}Input, idempotencyKey?: string): Promise<{{ execution_id: string; run_token: string }}> {{",
            "      const key = idempotencyKey ?? newKey()",
            "      return call<{ submission_id: string; execution_id: string; run_token: string }>(\"POST\", root + \"/submit\", {",
            "        body: { fields: input }, headers: { \"Idempotency-Key\": key },",
            "      }).then((r) => ({ execution_id: r.execution_id, run_token: r.run_token }))",
            "    },",
            f"    getRun(executionId: string, runToken: string): Promise<RunView<{P}Result>> {{",
            f"      return call<RunView<{P}Result>>(\"GET\", root + \"/runs/\" + encodeURIComponent(executionId), {{ headers: {{ Authorization: \"Bearer \" + runToken }} }})",
            "    },",
            "    /** Poll until the run succeeds, fails or is cancelled (a run waiting for a person keeps being polled). */",
            f"    async watchRun(executionId: string, runToken: string, onUpdate: (r: RunView<{P}Result>) => void, signal?: AbortSignal): Promise<RunView<{P}Result>> {{",
            "      const started = Date.now()",
            "      for (;;) {",
            f"        const view = await call<RunView<{P}Result>>(\"GET\", root + \"/runs/\" + encodeURIComponent(executionId), {{ headers: {{ Authorization: \"Bearer \" + runToken }} }})",
            "        onUpdate(view)",
            "        if (TERMINAL.indexOf(view.status) >= 0) return view",
            "        const age = Date.now() - started",
            "        await wait(age < 5000 ? 500 : age < 120000 ? 2000 : 10000, signal)",
            "      }",
            "    },",
        ]
    L += [
        "    listTasks(params: { status?: \"open\" | \"closed\" | \"all\"; cursor?: string; limit?: number } = {}): Promise<Page<TaskSummary>> {",
        "      return call<Page<TaskSummary>>(\"GET\", \"/api/tasks\" + qs({ project_id: PROJECT_ID || PROJECT, workflow_id: WORKFLOW_ID, status: params.status, cursor: params.cursor, limit: params.limit }))",
        "    },",
        "    getTask<N extends TaskNode>(taskId: string): Promise<TaskDetail<N>> {",
        "      return call<TaskDetail<N>>(\"GET\", \"/api/tasks/\" + encodeURIComponent(taskId))",
        "    },",
        "    approveTask<N extends TaskNode>(taskId: string, d: DecisionByNode[N] & { decided_by: string }, idempotencyKey?: string): Promise<DecideResult<N>> {",
        "      return call<DecideResult<N>>(\"POST\", \"/api/tasks/\" + encodeURIComponent(taskId) + \"/decide\", {",
        "        body: { ...d, decision: \"approved\" }, headers: { \"Idempotency-Key\": idempotencyKey ?? newKey() },",
        "      })",
        "    },",
        "    rejectTask<N extends TaskNode>(taskId: string, d: DecisionByNode[N] & { decided_by: string }, idempotencyKey?: string): Promise<DecideResult<N>> {",
        "      return call<DecideResult<N>>(\"POST\", \"/api/tasks/\" + encodeURIComponent(taskId) + \"/decide\", {",
        "        body: { ...d, decision: \"rejected\" }, headers: { \"Idempotency-Key\": idempotencyKey ?? newKey() },",
        "      })",
        "    },",
        "  }",
        "}",
        "",
        "export default createClient",
        "",
    ]
    return "\n".join(L)
