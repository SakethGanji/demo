"""Phase 6 (no LLM): the app builder's API context and declare_endpoint tool."""

from __future__ import annotations

from src.services.app_builder_ai_service import AppBuilderAIService, build_spec_summary
from src.services.api_usage import extract_api_calls
from src.services.client_codegen import generate_client

SPECS = [
    {"id": "r1", "name": "getOrdersById", "method": "GET", "path": "/orders/{id}", "auth": "app_token",
     "handler": {"type": "workflow"}, "response_schema": {"type": "object", "properties": {"id": {"type": "string"}}}},
    {"id": "r2", "name": "getAdminStats", "method": "GET", "path": "/admin/stats", "auth": "api_key", "handler": {"type": "workflow"}},
    {"id": "r3", "name": "createRefund", "method": "POST", "path": "/refunds", "auth": "none", "handler": {"type": "stub"}},
]


def test_spec_summary_lists_browser_callable_routes_only():
    s = build_spec_summary("shop", SPECS, focus={"r1"})
    assert "api.getOrdersById" in s and "← focus" in s and "stub" in s
    assert "getAdminStats" not in s and "./api/client" in s


def test_declare_endpoint_tool_requires_project_and_collects():
    svc = AppBuilderAIService.__new__(AppBuilderAIService)
    svc._project = None
    svc._declared = []
    assert "Error" in svc._execute_agent_tool("declare_endpoint", {"method": "GET", "path": "/x"}, [])
    svc._project = object()
    assert any(t["name"] == "declare_endpoint" for t in svc._build_agent_tools())
    out = svc._execute_agent_tool("declare_endpoint", {"method": "post", "path": "/refunds", "name": "createRefund"}, [])
    assert "Declared POST /refunds" in out and svc._declared[0]["method"] == "POST"


def test_client_codegen_and_usage_scan_roundtrip():
    src = generate_client("shop", SPECS, 3, "abc")
    assert src.startswith("/*! @generated by studio — spec rev 3, spec_hash abc")
    assert "getOrdersById" in src and "getAdminStats" not in src and "function qs(" in src
    calls = extract_api_calls("const x = api.getOrdersById({id:'1'})\nfetch(`/api/p/shop/orders/${id}`)\n", "shop")
    assert calls == [
        {"kind": "client_call", "operation": "getOrdersById", "method": None, "path": None, "line": 1},
        {"kind": "literal", "operation": None, "method": "GET", "path": "/orders/{_}", "line": 2},
    ]
